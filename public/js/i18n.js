  let currentLang = 'en';

  function setLanguage(lang) {
    if (!TRANSLATIONS[lang]) lang = 'en';
    currentLang = lang;
    const dict = TRANSLATIONS[lang];

    document.documentElement.lang = lang;

    const flagEl = document.getElementById('lang-flag');
    if (flagEl) flagEl.textContent = dict.flag || '🌐';
    const langSelect = document.getElementById('language-select');
    if (langSelect) langSelect.value = lang;

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.innerHTML = dict[key];
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    localStorage.setItem('pipetube_lang', lang);
  }

  async function autoDetectLanguage() {
    const saved = localStorage.getItem('pipetube_lang');
    if (saved && TRANSLATIONS[saved]) {
      setLanguage(saved);
      return;
    }

    const browserLang = (navigator.language || navigator.userLanguage || 'en').toLowerCase().split('-')[0];
    if (TRANSLATIONS[browserLang]) {
      setLanguage(browserLang);
    } else {
      setLanguage('en');
    }

    try {
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 1500);
      const res = await fetch('https://api.country.is', { signal: controller.signal });
      clearTimeout(timeoutId);

      if (res.ok) {
        const data = await res.json();
        const country = (data.country || '').toUpperCase();

        const countryMap = {
          ES: 'es', MX: 'es', AR: 'es', CO: 'es', CL: 'es', PE: 'es', VE: 'es',
          EC: 'es', GT: 'es', CU: 'es', BO: 'es', DO: 'es', HN: 'es', PY: 'es',
          SV: 'es', NI: 'es', CR: 'es', PA: 'es', UY: 'es', PR: 'es',
          BR: 'pt', PT: 'pt', AO: 'pt', MZ: 'pt',
          ID: 'id', MY: 'id',
          DE: 'de', AT: 'de', CH: 'de',
          FR: 'fr', BE: 'fr', SN: 'fr', CI: 'fr', CM: 'fr'
        };

        const detectedLang = countryMap[country];
        if (detectedLang && TRANSLATIONS[detectedLang]) {
          setLanguage(detectedLang);
        }
      }
    } catch (e) {
      // Ignore network timeout
    }
  }

  function initLangSelect() {
    const langSelect = document.getElementById('language-select');
    if (langSelect) {
      langSelect.addEventListener('change', (e) => {
        setLanguage(e.target.value);
      });
    }
  }

  window.PipeTubeI18n = {
    setLanguage,
    autoDetectLanguage,
    getDictionary: () => TRANSLATIONS[currentLang] || TRANSLATIONS.en,
    getCurrentLang: () => currentLang
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
      initLangSelect();
      autoDetectLanguage();
    });
  } else {
    initLangSelect();
    autoDetectLanguage();
  }
